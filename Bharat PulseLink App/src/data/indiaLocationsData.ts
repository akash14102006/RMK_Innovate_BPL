export const getIndiaStates = (): IndiaState[] => {
  return INDIA_LOCATIONS_DATA;
};

export const getDistrictsByState = (stateNameOrId: string): IndiaDistrict[] => {
  const normalized = (stateNameOrId || '').trim().toLowerCase();
  const foundState = INDIA_LOCATIONS_DATA.find(
    (s) =>
      s.id.toLowerCase() === normalized ||
      s.name.toLowerCase() === normalized ||
      s.code.toLowerCase() === normalized
  );

  if (!foundState) {
    return [];
  }

  return foundState.districts;
};

export const getCitiesByDistrict = (stateNameOrId: string, districtNameOrId: string): string[] => {
  const districts = getDistrictsByState(stateNameOrId);
  const normalizedDist = (districtNameOrId || '').trim().toLowerCase();

  const foundDist = districts.find(
    (d) => d.id.toLowerCase() === normalizedDist || d.name.toLowerCase() === normalizedDist
  );

  if (!foundDist) {
    return [];
  }

  return foundDist.cities;
};
